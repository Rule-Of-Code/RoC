/**
 * CapacitorSyncArtefactsMatchDependencies (#160): opens the native shell by fixed path,
 * although every fixture here excludes android/ and ios/ from the scan.
 */
import { CapacitorSyncArtefactsMatchDependenciesLaw } from '../../../src/checkers/capacitor-laws/capacitor-sync-artefacts-match-dependencies';
import { ctx, removeProjects } from '../toolkit-fixture';
import { IGNORING_SHELLS, capacitorProject, installPackage, track } from './capacitor-fixture';

afterAll(removeProjects);

describe('CapacitorSyncArtefactsMatchDependenciesLaw (#160)', () => {
  const GRADLE = 'android/capacitor.settings.gradle';
  const settings = (...pkgs: string[]) =>
    [
      '// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN',
      "include ':capacitor-android'",
      "project(':capacitor-android').projectDir = new File('../node_modules/@capacitor/android/capacitor')",
      ...pkgs.flatMap(pkg => [
        `include ':${pkg.replace('@capacitor/', 'capacitor-')}'`,
        `project(':${pkg.replace('@capacitor/', 'capacitor-')}').projectDir = new File('../node_modules/${pkg}/android')`,
      ]),
    ].join('\n');
  const setup = (deps: string[], included: string[], tracked = true) => {
    const root = capacitorProject(
      { [GRADLE]: settings(...included) },
      {},
      Object.fromEntries(deps.map(d => [d, '8.0.0']))
    );
    for (const dep of deps) installPackage(root, dep, { 'android/build.gradle': '' });
    if (tracked) track(root, GRADLE);
    return root;
  };
  const run = (root: string) => CapacitorSyncArtefactsMatchDependenciesLaw.check(ctx(root, IGNORING_SHELLS));

  it('red: a plugin added without a sync', () => {
    const result = run(setup(['@capacitor/app', '@capacitor/share'], ['@capacitor/app']));
    expect(result.violations).toEqual([
      expect.stringMatching(/^android\/capacitor\.settings\.gradle: @capacitor\/share is a dependency with a android\/ directory and is not in this file/),
    ]);
  });

  it('red: a plugin removed without a sync', () => {
    const result = run(setup(['@capacitor/app'], ['@capacitor/app', '@capacitor/camera']));
    expect(result.violations).toEqual([
      expect.stringContaining('references @capacitor/camera, which is not a dependency'),
    ]);
  });

  it('green: the tracked snapshot equals the dependencies', () => {
    expect(run(setup(['@capacitor/app', '@capacitor/share'], ['@capacitor/app', '@capacitor/share'])).violations).toEqual([]);
  });

  it('an untracked artefact is reported as not read, not as green', () => {
    const result = run(setup(['@capacitor/app', '@capacitor/share'], ['@capacitor/app'], false));
    expect(result.passed).toBe(true);
    expect(result.message).toContain('not read: android/capacitor.settings.gradle is not tracked');
  });

  it('a tracked Podfile is compared too', () => {
    const root = setup(['@capacitor/app'], ['@capacitor/app']);
    installPackage(root, '@capacitor/app', { 'ios/Plugin.swift': '' });
    require('fs').mkdirSync(require('path').join(root, 'ios', 'App'), { recursive: true });
    require('fs').writeFileSync(
      require('path').join(root, 'ios', 'App', 'Podfile'),
      "pod 'Capacitor', :path => '../../node_modules/@capacitor/ios'\n"
    );
    track(root, 'ios/App/Podfile');
    expect(run(root).violations).toEqual([
      expect.stringMatching(/^ios\/App\/Podfile: @capacitor\/app is a dependency with a ios\/ directory and is not in this file/),
    ]);
  });
});
