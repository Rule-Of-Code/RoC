/**
 * No tool attribution in this project's public text (scripts/public-text-guard.js).
 *
 * The founder's rule: no generated-with/by line naming the tool and no
 * Co-Authored-By trailer — not in a commit, a pull request, an issue, a
 * comment, a release note, the code or the docs. Agent tooling appends these
 * lines by default, so the rule is held by machinery, not by memory.
 *
 * The forbidden strings are assembled at run time below, so this file does not
 * contain the text it forbids.
 */
import fs from 'fs';
import os from 'os';
import path from 'path';

import { execFileSync, spawnSync } from '../../src/utils/child-process';

interface Hit {
  line: number;
  name: string;
  text: string;
  where?: string;
}
const guard = require('../../scripts/public-text-guard') as {
  findAttribution: (text: string) => Hit[];
  scanRepository: (
    repo: string,
    options: { fetchFn: (url: string) => Promise<unknown>; token?: string }
  ) => Promise<{ hits: Hit[]; read: Record<string, number> }>;
};

const REPO_ROOT = path.resolve(__dirname, '..', '..');
const SCRIPT = path.join(REPO_ROOT, 'scripts', 'public-text-guard.js');
const TOOL = ['Claude', 'Code'].join(' ');
const ATTRIBUTION = `🤖 ${['Generated', 'with'].join(' ')} [${TOOL}](https://example.invalid/tool)`;
const TRAILER = `${['Co', 'Authored', 'By'].join('-')}: Someone <someone@example.invalid>`;

describe('public-text guard: what it finds', () => {
  it.each([
    ['the line agent tooling appends', ATTRIBUTION],
    [
      'the same line without emoji and link',
      `${['Generated', 'with'].join(' ')} ${TOOL}`,
    ],
    [
      '"generated by", lower case',
      `${['generated', 'by'].join(' ')} ${TOOL.toLowerCase()}`,
    ],
    ['a Co-Authored-By trailer', TRAILER],
    ['an indented trailer', `    ${TRAILER}`],
    ['a quoted trailer', `> ${TRAILER}`],
  ])('finds %s', (_label, line) => {
    const hits = guard.findAttribution(`Summary\n\n${line}\n`);
    expect(hits).toHaveLength(1);
    expect(hits[0]?.line).toBe(3);
  });

  it.each([
    [
      'the rule written out inline',
      'No `Co-Authored-By` trailer. Not on any commit.',
    ],
    [
      'a sentence about generated files',
      'The registry is generated with a script.',
    ],
    ['an empty text', ''],
  ])('passes %s', (_label, text) => {
    expect(guard.findAttribution(text)).toEqual([]);
  });
});

describe('public-text guard: the command line', () => {
  let dir: string;
  beforeAll(() => {
    dir = fs.mkdtempSync(path.join(os.tmpdir(), 'roc-text-guard-'));
  });
  afterAll(() => fs.rmSync(dir, { recursive: true, force: true }));

  const run = (args: string[], input?: string) =>
    spawnSync(process.execPath, [SCRIPT, ...args], {
      cwd: dir,
      encoding: 'utf8',
      input,
    });

  it('exits 1 and names the file and the line of each hit', () => {
    const body = path.join(dir, 'body.md');
    fs.writeFileSync(body, `Fixes the thing.\n\n${ATTRIBUTION}\n`);
    const r = run([body]);
    expect(r.status).toBe(1);
    expect(r.stdout).toContain(`${body}:3: tool attribution line`);
  });

  it('exits 0 on clean text, from a file and from stdin', () => {
    const body = path.join(dir, 'clean.md');
    fs.writeFileSync(body, 'Fixes the thing.\n');
    expect(run([body]).status).toBe(0);
    expect(run(['-'], 'Fixes the thing.\n').status).toBe(0);
  });

  it('exits 1 on stdin with a trailer', () => {
    expect(run(['-'], `Subject\n\n${TRAILER}\n`).status).toBe(1);
  });

  it('exits 2, not 0, when it was given nothing to check', () => {
    expect(run([]).status).toBe(2);
  });
});

describe('public-text guard: --scan reads every page and fails closed', () => {
  const page = (items: unknown[]) => ({
    ok: true,
    status: 200,
    json: async () => items,
  });

  it('reports a hit in a comment, with where it is', async () => {
    const fetchFn = async (url: string) =>
      page(
        url.includes('/issues/comments')
          ? [
              {
                html_url: 'https://example.invalid/c/1',
                body: `ok\n${TRAILER}`,
              },
            ]
          : url.includes('/issues?')
            ? [{ number: 7, title: 'A title', body: 'clean' }]
            : []
      );
    const { hits, read } = await guard.scanRepository('o/r', { fetchFn });
    expect(hits).toHaveLength(1);
    expect(hits[0]?.where).toBe('https://example.invalid/c/1 (body)');
    expect(read['issues?state=all']).toBe(1);
  });

  it('reads past the first page', async () => {
    const urls: string[] = [];
    const full = Array.from({ length: 100 }, (_, i) => ({
      number: i,
      title: 't',
      body: 'b',
    }));
    const fetchFn = async (url: string) => {
      urls.push(url);
      if (url.includes('/issues?') && url.endsWith('page=1')) return page(full);
      if (url.includes('/issues?') && url.endsWith('page=2'))
        return page([{ number: 100, title: 't', body: ATTRIBUTION }]);
      return page([]);
    };
    const { hits, read } = await guard.scanRepository('o/r', { fetchFn });
    expect(read['issues?state=all']).toBe(101);
    expect(hits.map(h => h.where)).toEqual(['#100 (body)']);
  });

  it('throws when a page cannot be read — a skipped page is not a clean one', async () => {
    const fetchFn = async () => ({
      ok: false,
      status: 403,
      json: async () => ({}),
    });
    await expect(guard.scanRepository('o/r', { fetchFn })).rejects.toThrow(
      'HTTP 403'
    );
  });
});

describe('public-text guard: the repository itself', () => {
  it('no tracked file carries tool attribution', () => {
    let files: string[];
    try {
      files = execFileSync('git', ['ls-files', '-z'], {
        cwd: REPO_ROOT,
        encoding: 'utf8',
        maxBuffer: 64 * 1024 * 1024,
      })
        .split('\0')
        .filter(Boolean);
    } catch {
      console.warn(
        '⚠️  no git repository here — tracked files cannot be listed.'
      );
      return;
    }
    expect(files.length).toBeGreaterThan(100);
    const offenders: string[] = [];
    for (const file of files) {
      const full = path.join(REPO_ROOT, file);
      let text: string;
      try {
        const buf = fs.readFileSync(full);
        if (buf.includes(0)) continue; // binary (a GIF, a font)
        text = buf.toString('utf8');
      } catch {
        continue; // listed but absent in this checkout
      }
      for (const hit of guard.findAttribution(text))
        offenders.push(`${file}:${hit.line}: ${hit.name}`);
    }
    expect(offenders).toEqual([]);
  });
});
